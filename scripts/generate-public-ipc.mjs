#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import ts from 'typescript';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const contractPath = 'apps/desktop/src/ipc/publicContract.ts';
const generatedNotice = '// Generated by scripts/generate-public-ipc.mjs. Edit ipc/publicContract.ts instead.\n';

/** Parse the typed public contract without executing it or discovering main handlers. */
export function renderPublicIpc(sourceText) {
  // Checkout line endings are transport; keep every other source byte significant.
  sourceText = sourceText.replace(/\r\n/g, '\n');
  const source = ts.createSourceFile(contractPath, sourceText, ts.ScriptTarget.Latest, true);
  if (source.parseDiagnostics.length) throw new Error('PUBLIC_IPC_CONTRACT_SYNTAX_INVALID');
  const text = (node) => node.getText(source);
  const declaration = source.statements
    .filter(ts.isVariableStatement)
    .flatMap((statement) => [...statement.declarationList.declarations])
    .find((entry) => ts.isIdentifier(entry.name) && entry.name.text === 'publicIpcContract');
  let object = declaration?.initializer;
  if (object && ts.isAsExpression(object)) object = object.expression;
  if (!object || !ts.isObjectLiteralExpression(object)) throw new Error('PUBLIC_IPC_CONTRACT_OBJECT_REQUIRED');

  const imports = source.statements.filter(ts.isImportDeclaration).filter((entry) => entry.moduleSpecifier.text !== './contractDefinition.js')
    .map((entry) => text(entry).replace(/from '\.\/publicTypes\.js'/g, "from '../ipc/publicTypes.js'"));
  const methods = [];
  const names = new Set();
  let usesTransform = false;
  for (const property of object.properties) {
    if (!ts.isPropertyAssignment(property) || !ts.isIdentifier(property.name)) throw new Error('PUBLIC_IPC_NAMED_METHOD_REQUIRED');
    const name = property.name.text;
    if (names.has(name) || ['__proto__', 'prototype', 'constructor', 'invoke', 'send', 'handle'].includes(name)) {
      throw new Error(`PUBLIC_IPC_METHOD_INVALID: ${name}`);
    }
    names.add(name);
    const entry = property.initializer;
    if (!ts.isCallExpression(entry)) throw new Error(`PUBLIC_IPC_DESCRIPTOR_REQUIRED: ${name}`);
    const [channel, mapping, transform] = entry.arguments;
    if (!channel || !(ts.isStringLiteral(channel) || ts.isPropertyAccessExpression(channel))) throw new Error(`PUBLIC_IPC_CHANNEL_INVALID: ${name}`);
    if (!mapping || !ts.isArrowFunction(mapping)) throw new Error(`PUBLIC_IPC_MAPPING_REQUIRED: ${name}`);

    if (ts.isCallExpression(entry.expression) && ts.isIdentifier(entry.expression.expression) && entry.expression.expression.text === 'invoke') {
      if (entry.expression.typeArguments?.length !== 1 || entry.expression.arguments.length !== 0 || entry.arguments.length > 3) {
        throw new Error(`PUBLIC_IPC_RESULT_REQUIRED: ${name}`);
      }
      if (!ts.isArrayLiteralExpression(mapping.body) || mapping.body.elements.some(ts.isSpreadElement)
        || mapping.parameters.some((parameter) => !ts.isIdentifier(parameter.name) || parameter.dotDotDotToken)) {
        throw new Error(`PUBLIC_IPC_FIXED_ARGUMENTS_REQUIRED: ${name}`);
      }
      if (transform && (!ts.isStringLiteral(transform) || transform.text !== 'stripPathFields')) throw new Error(`PUBLIC_IPC_TRANSFORM_INVALID: ${name}`);
      usesTransform ||= !!transform;
      const params = mapping.parameters.map(text).join(', ');
      const result = text(entry.expression.typeArguments[0]);
      const wireArgs = [...mapping.body.elements].map(text);
      methods.push(`  ${name}: (${params}): Promise<${result}> =>\n    ipcRenderer.invoke(${[text(channel), ...wireArgs].join(', ')})${transform ? '.then(stripPathFields)' : ''}`);
    } else if (ts.isIdentifier(entry.expression) && entry.expression.text === 'subscribe') {
      if (entry.typeArguments?.length !== 2 || entry.arguments.length < 2 || entry.arguments.length > 3 || mapping.parameters.length !== 1 || !ts.isIdentifier(mapping.parameters[0].name)) {
        throw new Error(`PUBLIC_IPC_EVENT_PROJECTION_REQUIRED: ${name}`);
      }
      if (transform && (!ts.isStringLiteral(transform) || !['transport', 'void'].includes(transform.text))) {
        throw new Error(`PUBLIC_IPC_UNSUBSCRIBE_INVALID: ${name}`);
      }
      const [envelope, value] = entry.typeArguments.map(text);
      const argument = text(mapping.parameters[0].name);
      const remove = `ipcRenderer.removeListener(${text(channel)}, listener)`;
      const unsubscribe = transform?.text === 'transport' ? `${remove};` : `{ ${remove}; };`;
      methods.push(`  ${name}: (callback: (value: ${value}) => void): (() => void) => {\n    const listener = (_event: Electron.IpcRendererEvent, ${argument}: ${envelope}): void => {\n      callback(${text(mapping.body)});\n    };\n    ipcRenderer.on(${text(channel)}, listener);\n    return () => ${unsubscribe}\n  }`);
    } else {
      throw new Error(`PUBLIC_IPC_DESCRIPTOR_INVALID: ${name}`);
    }
  }
  if (names.size === 0) throw new Error('PUBLIC_IPC_CONTRACT_EMPTY');

  return new Map([
    ['apps/desktop/src/preload/index.ts', `${generatedNotice}import { contextBridge, ipcRenderer } from 'electron';\n${imports.join('\n')}\nimport type { SoulForgeApi } from '../ipc/publicApi.generated.js';\n${usesTransform ? "import { stripPathFields } from './resultTransforms.js';\n" : ''}\nconst api: SoulForgeApi = {\n${methods.join(',\n')}\n};\n\ncontextBridge.exposeInMainWorld('soulforge', api);\n\nexport type { SoulForgeApi } from '../ipc/publicApi.generated.js';\nexport type { MapReadCancellationResult } from '../ipc/publicTypes.js';\n`],
    ['apps/desktop/src/ipc/publicApi.generated.ts', `${generatedNotice}import type { ContractApi } from './contractDefinition.js';\nimport type { publicIpcContract } from './publicContract.js';\n\nexport type SoulForgeApi = ContractApi<typeof publicIpcContract>;\n`]
  ]);
}

export function checkPublicIpcOutputs(root, outputs) {
  const stale = [];
  for (const [path, expected] of outputs) {
    let current;
    try { current = readFileSync(resolve(root, path), 'utf8'); } catch { /* Missing output is stale. */ }
    if (current?.replace(/\r\n/g, '\n') !== expected) stale.push(path);
  }
  return stale;
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
  const args = process.argv.slice(2);
  if (args.some((arg) => arg !== '--check')) throw new Error('Usage: node scripts/generate-public-ipc.mjs [--check]');
  const outputs = renderPublicIpc(readFileSync(resolve(repoRoot, contractPath), 'utf8'));
  if (args.includes('--check')) {
    const stale = checkPublicIpcOutputs(repoRoot, outputs);
    if (stale.length) {
      console.error(`Public IPC projections are stale: ${stale.join(', ')}\nRun node scripts/generate-public-ipc.mjs`);
      process.exitCode = 1;
    } else console.log('Public IPC projections are current');
  } else {
    for (const [path, output] of outputs) writeFileSync(resolve(repoRoot, path), output);
    console.log(`Generated ${outputs.size} public IPC projections`);
  }
}
