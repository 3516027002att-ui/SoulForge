import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function generateBridgeCommands(manifest) {
  if (manifest.schemaVersion !== 1 || !Array.isArray(manifest.commands) || !manifest.commands.length) throw new Error('BRIDGE_COMMAND_MANIFEST_INVALID');
  const names = new Set();
  for (const command of manifest.commands) {
    if (!/^[a-z][a-z0-9-]*$/.test(command.name) || names.has(command.name)
      || !['read', 'write', 'export'].includes(command.effect)
      || !['service', 'artifact'].includes(command.handler)
      || !['interactive', 'foreground', 'background'].includes(command.costClass)
      || command.cancelMode !== 'cooperative' || typeof command.advertised !== 'boolean'
      || typeof command.requiresOutputPath !== 'boolean'
      || command.effect === 'write' && !command.requiresOutputPath
      || !Array.isArray(command.requiredInputFields) || command.requiredInputFields.length < 2
      || command.requiresOutputPath && (command.effect === 'read' || !command.requiredInputFields.includes('options.outputPath'))) throw new Error(`BRIDGE_COMMAND_MANIFEST_INVALID: ${command.name}`);
    names.add(command.name);
  }
  const csString = value => JSON.stringify(value);
  const cs = '// Generated by scripts/generate-bridge-commands.mjs from bridge/commands.json. Do not edit.\n'
    + 'internal static class BridgeCommandDefinitions\n{\n    internal static readonly IReadOnlyList<BridgeCommandDescriptor> All = new BridgeCommandDescriptor[]\n    {\n'
    + manifest.commands.map(command => `        new() { Name = ${csString(command.name)}, Effect = ${csString(command.effect)}, Advertised = ${command.advertised}, RequiredInputFields = new[] { ${command.requiredInputFields.map(csString).join(', ')} }, RequiresOutputPath = ${command.requiresOutputPath}, CostClass = ${csString(command.costClass)}, CancelMode = ${csString(command.cancelMode)}, Handler = ${csString(command.handler === 'artifact' ? 'BridgeDaemonHost.DaemonState.ReadArtifactAsync' : 'BridgeCommandService.ExecuteAsync')} },`).join('\n')
    + '\n    };\n}\n';
  const ts = '// Generated by scripts/generate-bridge-commands.mjs from bridge/commands.json. Do not edit.\n'
    + `export const BRIDGE_FILE_COMMANDS = ${JSON.stringify([...names], null, 2)} as const;\nexport type BridgeFileCommandName = typeof BRIDGE_FILE_COMMANDS[number];\n`;
  return new Map([['bridge/SoulForge.Bridge/BridgeCommandDefinitions.generated.cs', cs], ['packages/shared/src/bridge-commands.generated.ts', ts]]);
}

export async function checkOrWriteBridgeCommands({ check = false } = {}) {
  const outputs = generateBridgeCommands(JSON.parse(await readFile(resolve(root, 'bridge/commands.json'), 'utf8')));
  for (const [file, source] of outputs) {
    if (check) {
      if (await readFile(resolve(root, file), 'utf8').catch(() => '') !== source) throw new Error(`BRIDGE_COMMAND_GENERATED_STALE: ${file}`);
    } else await writeFile(resolve(root, file), source);
  }
  return { ok: true, commands: JSON.parse(await readFile(resolve(root, 'bridge/commands.json'), 'utf8')).commands.length, evidence: 'generated-contract-consistency; actual dispatch is covered by C# tests' };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  console.log(JSON.stringify(await checkOrWriteBridgeCommands({ check: process.argv.includes('--check') })));
}
